# frozen_string_literal: true

require "tempfile"

module Sevgi
  module Sundries
    module Export
      # Places A5 PDF pages on A4 landscape sheets with pdfcpu.
      # @param infile [String] source PDF file path
      # @param outfile [String] destination PDF file path
      # @return [Sevgi::Function::Shell::Result] command result
      # @raise [Sevgi::Error] when pdfcpu is missing or the command fails
      # @raise [Errno::ENOENT] when the executable cannot be spawned
      # @see https://pdfcpu.io/ pdfcpu
      def a5_on_a4(infile, outfile)
        F.sh!("pdfcpu", "nup", "--conf", "disable", "--", "form:A4L, border:off", outfile, "2", infile)
      end

      # Replaces a PDF file with an A5-on-A4 layout generated by pdfcpu.
      # @param infile [String] PDF file path to modify
      # @return [void]
      # @raise [Sevgi::Error] when pdfcpu is missing or the command fails
      # @raise [Errno::ENOENT] when the executable cannot be spawned
      def a5_on_a4!(infile)
        Staging.replace(infile, prefix: ".sevgi-nup-", filename: "output.pdf") do |outfile|
          a5_on_a4(infile, outfile)
          true
        end

        nil
      end

      # Exports an SVG file through Inkscape.
      # @param infile [String] source SVG file path
      # @param outfile [String, nil] output path, defaulting to infile with the format extension (or .pdf when format is omitted)
      # @param format [Symbol, String, nil] explicit output format, or nil to infer from outfile
      # @param background [String, nil] export background color
      # @param opacity [Numeric, nil] export background opacity
      # @param width [Numeric, nil] target export width
      # @param height [Numeric, nil] target export height
      # @param id [String, nil] SVG element id to export
      # @param page [Integer, String, nil] page selector passed to Inkscape
      # @param css [String, nil] CSS inserted before exporting
      # @return [Sevgi::Function::Shell::Result] command result
      # @raise [Sevgi::Sundries::Export::ExportError] when format, output extension, or CSS insertion is invalid
      # @raise [Sevgi::Error] when Inkscape is missing or the command fails
      # @raise [Errno::ENOENT] when the executable cannot be spawned
      # @see https://inkscape.org/ Inkscape
      def inkscape(
        infile,
        outfile = nil,
        format: nil,
        background: "#ffffff",
        opacity: 1,
        width: nil,
        height: nil,
        id: nil,
        page: nil,
        css: nil
      )
        infile, outfile, format = prepare_paths(infile, outfile, format)

        with_staged_svg(infile, css) do |source|
          F.sh!(
            *[
              "inkscape",
              "--batch-process",
              "--actions=select-by-class:text,object-to-path",
              "--export-type=#{format}",
              ("--export-background=#{background}" if background),
              ("--export-background-opacity=#{opacity}" if opacity),
              ("--export-width=#{width}" if width),
              ("--export-height=#{height}" if height),
              ("--export-id=#{id}" if id),
              ("--export-id-only" if id),
              ("--export-page=#{page}" if page),
              "--export-filename=#{outfile}",
              source
            ].compact
          )
        end
      end

      # Exports an SVG file through rsvg-convert.
      # @param infile [String] source SVG file path
      # @param outfile [String, nil] output path, defaulting to infile with the format extension (or .pdf when format is omitted)
      # @param format [Symbol, String, nil] explicit output format, or nil to infer from outfile
      # @param background [String, nil] export background color
      # @param width [Numeric, nil] target export width
      # @param height [Numeric, nil] target export height
      # @param id [String, nil] SVG element id to export
      # @param css [String, nil] CSS inserted before exporting
      # @return [Sevgi::Function::Shell::Result] command result
      # @raise [Sevgi::Sundries::Export::ExportError] when format, output extension, or CSS insertion is invalid
      # @raise [Sevgi::Error] when rsvg-convert is missing or the command fails
      # @raise [Errno::ENOENT] when the executable cannot be spawned
      # @see https://gitlab.gnome.org/GNOME/librsvg librsvg
      def rsvg(
        infile,
        outfile = nil,
        format: nil,
        background: "#ffffff",
        width: nil,
        height: nil,
        id: nil,
        css: nil
      )
        infile, outfile, format = prepare_paths(infile, outfile, format)

        with_staged_svg(infile, css) do |source|
          F.sh!(
            *[
              "rsvg-convert",
              "--format=#{format}",
              ("--background-color=#{background}" if background),
              ("--width=#{width}" if width),
              ("--height=#{height}" if height),
              ("--export-id=#{id}" if id),
              "--output=#{outfile}",
              source
            ].compact
          )
        end
      end

      # Merges PDF files with pdfunite.
      # @param sources [Array<String>] source PDF file paths
      # @param outfile [String] destination PDF file path
      # @return [Sevgi::Function::Shell::Result] command result
      # @raise [Sevgi::Error] when pdfunite is missing or the command fails
      # @raise [Errno::ENOENT] when the executable cannot be spawned
      # @see https://poppler.freedesktop.org/ Poppler
      def unite(sources, outfile) = F.sh!("pdfunite", *sources, outfile)

      private

      def prepare_paths(infile, outfile, format)
        infile = File.expand_path(infile)

        if outfile
          outfile = File.expand_path(outfile)
          [infile, outfile, format_for(format, outfile)]
        else
          format = format ? format_for(format, nil) : :pdf
          [infile, F.subext(AVAILABLE.fetch(format), infile), format]
        end
      end

      def with_staged_svg(infile, css)
        return yield(infile) unless css

        ::Tempfile.create([".sevgi-css-", ".svg"], ::File.dirname(infile)) do |staged|
          staged.write(styled(::File.read(infile), css))
          staged.close
          yield(staged.path)
        end
      end

      extend self
    end
  end
end
